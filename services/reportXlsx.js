// Excel export (D-297 IMPL-5 Part 3; UC-20 "PDF or Excel").
// Formula injection safety: same rule as csvRules.js — cells that would run as a formula get a
// leading apostrophe (OWASP); plain numbers stay as Excel numbers. No AI score, no email, no DB id
// (safeAiText from reportPdf.js handles the AI summary).
import ExcelJS from "exceljs";

const NUMBER = /^[+-]?\d+(\.\d+)?( XP|%)?$/;
// Return a value safe for an Excel cell: numbers as JS numbers, strings as strings (formula-prefixed if needed).
function xlCell(v) {
  const s = String(v ?? "");
  if (NUMBER.test(s)) return parseFloat(s.replace(/ XP$|%$/, "")) || 0;
  if (/^[=+\-@\t\r]/.test(s)) return `'${s}`;
  return s;
}

// Builds an .xlsx Buffer from the exportDoc shape:
// doc = { title, filters, sections: [{ heading, headers, rows }] }
// extra = { orgName?, aiSummary?, generatedBy? }
export async function buildReportXlsx(doc, { orgName = "", aiSummary, generatedBy = "" } = {}) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "ACHIEVION";
  wb.created = new Date();

  // ── Summary sheet ────────────────────────────────────────────────────────────
  const summary = wb.addWorksheet("Summary");
  summary.getColumn(1).width = 22;
  summary.getColumn(2).width = 60;

  const addRow = (label, value) => {
    const r = summary.addRow([label, value]);
    r.getCell(1).font = { bold: true };
  };

  if (orgName) addRow("Organization", orgName);
  addRow("Report", doc.title ?? "");
  if (doc.filters) addRow("Period / scope", doc.filters);
  addRow("Generated", new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC");
  if (generatedBy) addRow("Generated by", generatedBy);

  if (aiSummary !== undefined) {
    summary.addRow([]);
    addRow("AI summary", aiSummary ?? "AI summary not available");
    if (aiSummary) {
      const note = summary.addRow(["", "AI-generated from the numbers in this report. Check the tables before you act on it."]);
      note.getCell(2).font = { italic: true, color: { argb: "FF475467" } };
    }
  }

  // ── One sheet per section ─────────────────────────────────────────────────
  const usedNames = new Set(["Summary"]);
  for (const section of doc.sections ?? []) {
    let name = (section.heading ?? "Sheet").slice(0, 31).replace(/[\\/?*[\]:]/g, " ");
    if (usedNames.has(name)) name = name.slice(0, 28) + " (2)";
    usedNames.add(name);
    const ws = wb.addWorksheet(name);

    // Header row — bold + light fill
    const headerRow = ws.addRow((section.headers ?? []).map(xlCell));
    headerRow.eachCell((cell) => {
      cell.font = { bold: true };
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE4E7EC" } };
    });

    // Data rows
    for (const row of section.rows ?? []) {
      ws.addRow(row.map(xlCell));
    }

    // Auto-width: set each column to the max content length (capped at 60)
    ws.columns.forEach((col, i) => {
      const maxLen = (section.rows ?? []).reduce(
        (m, r) => Math.max(m, String(r[i] ?? "").length),
        (section.headers?.[i] ?? "").length,
      );
      col.width = Math.min(Math.max(maxLen + 2, 10), 60);
    });
  }

  return wb.xlsx.writeBuffer();
}
